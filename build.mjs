import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync(new URL('./src/index.html', import.meta.url), 'utf8');
const css = readFileSync(new URL('./src/styles.css', import.meta.url), 'utf8');
const js = readFileSync(new URL('./src/app.js', import.meta.url), 'utf8');
const appIcon = readFileSync(new URL('./src/app-icon.svg', import.meta.url), 'utf8');
const appIconUrl = 'data:image/svg+xml;base64,' + Buffer.from(appIcon).toString('base64');
const manifest = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8'));
const stylesheetTag = '<link rel="stylesheet" href="styles.css" />';
const appInfoTag = '<script src="app-info.js"></script>';
const holidayDataTag = '<script src="holiday-data.js"></script>';
const scriptTag = '<script src="app.js"></script>';
const faviconTag = '<link rel="icon" type="image/svg+xml" href="app-icon.svg" />';
const appLogoSource = 'src="app-icon.svg"';

if (!html.includes(stylesheetTag) || !html.includes(appInfoTag) || !html.includes(holidayDataTag) || !html.includes(scriptTag)) {
	throw new Error('Expected stylesheet and script tags were not found in src/index.html.');
}
if (!html.includes(faviconTag) || !html.includes(appLogoSource)) {
	throw new Error('Expected favicon and app logo tags were not found in src/index.html.');
}

if (typeof manifest.version !== 'string' || !/^\d+\.\d+\.\d+(?:-[\w.-]+)?(?:\+[\w.-]+)?$/.test(manifest.version)) {
	throw new Error('package.json must contain a semantic app version.');
}
if (typeof manifest.publishedDate !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(manifest.publishedDate) ||
	new Date(manifest.publishedDate + 'T00:00:00Z').toISOString().slice(0, 10) !== manifest.publishedDate) {
	throw new Error('package.json must contain a valid publishedDate in YYYY-MM-DD format.');
}
const appInfo = '// Generated by build.mjs from package.json.\nconst BELT_APP_INFO = Object.freeze('
	+ JSON.stringify({ version: manifest.version, publishedDate: manifest.publishedDate }) + ');\n';
writeFileSync(new URL('./src/app-info.js', import.meta.url), appInfo, 'utf8');

const holidayData = JSON.parse(readFileSync(new URL('./src/corporate-holidays-2026-2027.json', import.meta.url), 'utf8'));
if (typeof holidayData.source.retrievedAt !== 'string' || !isDateKey(holidayData.source.retrievedAt.slice(0, 10)) ||
	!Number.isFinite(Date.parse(holidayData.source.retrievedAt))) {
	throw new Error('Holiday data must contain a valid source retrieval date.');
}
const locationKeys = new Set();
for (const geo of holidayData.geos) {
	const codes = [geo.countryCode, geo.companyCode, geo.personnelSubAreaCode];
	const key = codes.join(':');
	if (codes.some(code => typeof code !== 'string' || !code.trim()) ||
		typeof geo.name !== 'string' || !geo.name.trim() ||
		locationKeys.has(key) || !Object.hasOwn(holidayData.calendars, geo.calendarId)) {
		throw new Error('Invalid or duplicate holiday location: ' + key);
	}
	locationKeys.add(key);
}
function isDateKey(value) {
	return typeof value === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(value) &&
		Number.isFinite(Date.parse(value)) && new Date(value).toISOString().slice(0, 10) === value;
}
for (const [id, calendar] of Object.entries(holidayData.calendars)) {
	const years = new Set();
	for (const holiday of calendar.holidays) {
		if (!isDateKey(holiday.startDate) || !isDateKey(holiday.endDate) ||
			holiday.startDate > holiday.endDate || typeof holiday.name !== 'string' || !holiday.name.trim()) {
			throw new Error('Invalid holiday in ' + id + ': ' + JSON.stringify(holiday));
		}
		for (let year = Number(holiday.startDate.slice(0, 4)); year <= Number(holiday.endDate.slice(0, 4)); year++) {
			years.add(String(year));
		}
	}
	if (JSON.stringify([...years].sort()) !== JSON.stringify([...calendar.availableYears].sort())) {
		throw new Error('Holiday coverage does not match the dates in ' + id);
	}
}
const holidayScript = '// Generated by build.mjs from corporate-holidays-2026-2027.json. Do not edit.\n'
	+ 'const BELT_HOLIDAY_DATA = ' + JSON.stringify(holidayData).replace(/</g, '\\u003c')
		.replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029') + ';\n';
writeFileSync(new URL('./src/holiday-data.js', import.meta.url), holidayScript, 'utf8');

const bundled = html
	.replace(faviconTag, () => faviconTag.replace('app-icon.svg', appIconUrl))
	.replaceAll(appLogoSource, () => 'src="' + appIconUrl + '"')
	.replace(stylesheetTag, () => `<style>\n${css}\n</style>`)
	.replace(appInfoTag, () => `<script>\n${appInfo}\n</script>`)
	.replace(holidayDataTag, () => `<script>\n${holidayScript}\n</script>`)
	.replace(scriptTag, () => `<script>\n${js}\n</script>`);

const dist = new URL('./dist/', import.meta.url);
mkdirSync(dist, { recursive: true });
writeFileSync(new URL('index.html', dist), bundled, 'utf8');
console.log('Built dist/index.html');
